/** Translate without React (used by the store to write English text into records). */
export function tr(lang, key, vars) {
  // Stage names the administrator chose win over the built-in ones.
  const stage = /^(status|flow)\.(.+)$/.exec(key);
  const custom = key.startsWith('reason.') ? customReasonLabel(key.slice(7)) : null;
  const s = custom ?? (stage && stageText(stage[1], stage[2])) ?? STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : s;
}

const KEY = 'unifiedtree-scm-lang';
const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      return localStorage.getItem(KEY) === 'hi' ? 'hi' : 'en';
    } catch {
      return 'en';
    }
  });

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l) => {
    try {
      localStorage.setItem(KEY, l);
    } catch {
      /* ignore */
    }
    setLangState(l);
  }, []);

  // Names the administrator gave to sections; they replace the built-in label in every language.
  const [overrides, setOverridesState] = useState({});
  const setOverrides = useCallback((o) => setOverridesState(o ?? {}), []);

  const value = useMemo(
    () => ({
      lang,
      setLang,
      setOverrides,
      t: (key, vars) => (overrides[key] ? overrides[key] : tr(lang, key, vars)),
    }),
    [lang, setLang, overrides, setOverrides],
  );
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}
